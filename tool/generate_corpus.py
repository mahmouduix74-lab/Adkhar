# -*- coding: utf-8 -*-
"""Builds the offline knowledge the assistant searches, beyond the Quran text
it already has.

Outputs (all cited in the app's Sources screen):
  assets/corpus/hisn_full.json     — every chapter of حصن المسلم (hisnmuslim.com)
  assets/corpus/tafsir_muyassar.json — التفسير الميسّر, all 6236 ayat (alquran.cloud / KSU)
  lib/data/islamic_corpus.dart     — الأربعون النووية, 42 hadith (fawazahmed0/hadith-api, CC0)

Run:  python3 tool/generate_corpus.py
"""
import json
import re
import subprocess
import sys

_BIDI = re.compile('[\u200e\u200f\u202a-\u202e\u2066-\u2069]')


def _clean(s):
    return _BIDI.sub('', ' '.join((s or '').split()))

HISN = "https://www.hisnmuslim.com/api/ar/{}.json"
HISN_LAST = 132
MUYASSAR = "https://api.alquran.cloud/v1/quran/ar.muyassar"
NAWAWI = "https://cdn.jsdelivr.net/gh/fawazahmed0/hadith-api@1/editions/ara-nawawi.min.json"


def fetch(url, bom=False):
    out = subprocess.run(["curl", "-s", "--max-time", "90", url],
                         capture_output=True, check=True).stdout
    return json.loads(out.decode("utf-8-sig" if bom else "utf-8"))


def build_hisn():
    chapters = []
    for n in range(1, HISN_LAST + 1):
        try:
            data = fetch(HISN.format(n), bom=True)
        except Exception:
            print(f"  ! chapter {n} failed, skipped", file=sys.stderr)
            continue
        title = list(data.keys())[0]
        items = []
        for it in list(data.values())[0]:
            text = _clean(it.get("ARABIC_TEXT"))
            if not text:
                continue
            items.append({"text": text, "repeat": int(it.get("REPEAT") or 1)})
        if items:
            chapters.append({"n": n, "title": title.strip(), "items": items})
    return chapters


def build_muyassar():
    data = fetch(MUYASSAR)["data"]
    out = {}
    for surah in data["surahs"]:
        s = surah["number"]
        for ayah in surah["ayahs"]:
            out[f'{s}:{ayah["numberInSurah"]}'] = _clean(ayah["text"])
    return out


def build_nawawi():
    data = fetch(NAWAWI)
    out = []
    for h in data["hadiths"]:
        text = _clean(h.get("text"))
        if text:
            out.append({"n": h["hadithnumber"], "text": text})
    return out


def dart_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", r"\$") + '"'


def main():
    print("hisn al-muslim…")
    hisn = build_hisn()
    json.dump(hisn, open("assets/corpus/hisn_full.json", "w", encoding="utf-8"),
              ensure_ascii=False, separators=(",", ":"))
    print(f"  {len(hisn)} chapters, {sum(len(c['items']) for c in hisn)} du'a")

    print("tafsir al-muyassar…")
    muy = build_muyassar()
    json.dump(muy, open("assets/corpus/tafsir_muyassar.json", "w", encoding="utf-8"),
              ensure_ascii=False, separators=(",", ":"))
    print(f"  {len(muy)} ayat")

    print("nawawi 42…")
    naw = build_nawawi()
    lines = ",\n".join(
        f"  _Hadith({h['n']}, {dart_str(h['text'])})" for h in naw)
    dart = (
        "// GENERATED by tool/generate_corpus.py — do not hand-edit.\n"
        "//\n"
        "// الأربعون النووية (بزيادة ابن رجب، 42 حديثًا). النص من مجموعة\n"
        "// hadith-api (fawazahmed0) المتاحة تحت CC0. متن الأحاديث فقط —\n"
        "// المتن متواتر ومشهور، والتخريج والحكم مرجعهما كتب أهل العلم.\n"
        "\n"
        "class _Hadith {\n"
        "  final int number;\n"
        "  final String text;\n"
        "  const _Hadith(this.number, this.text);\n"
        "}\n"
        "\n"
        f"const List<_Hadith> nawawiForty = [\n{lines},\n];\n"
    )
    open("lib/data/islamic_corpus.dart", "w", encoding="utf-8").write(dart)
    print(f"  {len(naw)} hadith")


if __name__ == "__main__":
    main()
